/** Import report for all PSI run tables: combined totals plus one section per investigation. */
import type { Run } from "../lib/schema";
import type { Skipped } from "./psi_import_bass";

export type ReportGroup = {
  psiId: string;
  name: string;
  file: string;
  url: string;
  runs: Run[];
  skipped: Skipped[];
};

const count = <T,>(items: T[]) => {
  const m = new Map<T, number>();
  for (const i of items) m.set(i, (m.get(i) ?? 0) + 1);
  return m;
};
const table = (head: string[], rows: (string | number)[][]) =>
  [
    `| ${head.join(" | ")} |`,
    `|${head.map((_, i) => (i === 0 ? "---" : "---:")).join("|")}|`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");

/** Group flags whose text embeds a raw value, so totals count the kind of flag. */
const flagKind = (f: string) => f.replace(/\(raw: .*\)$/, "(raw: …)");

const BANDS: [string, (v: number) => boolean][] = [
  ["< 15", (v) => v < 15],
  ["15–17", (v) => v >= 15 && v < 17],
  ["17–19", (v) => v >= 17 && v < 19],
  ["19–21", (v) => v >= 19 && v < 21],
  ["21–23", (v) => v >= 21 && v < 23],
  ["≥ 23", (v) => v >= 23],
];

function o2Rows(runs: Run[]): (string | number)[][] {
  const rows: (string | number)[][] = BANDS.map(([label, f]) => [
    label,
    runs.filter((r) => r.o2InitialPct !== null && f(r.o2InitialPct)).length,
  ]);
  rows.push(["not recorded", runs.filter((r) => r.o2InitialPct === null).length]);
  return rows;
}

function section(g: ReportGroup): string {
  const { runs } = g;
  const flagged = runs.filter((r) => r.flags.length);
  const universal = [...new Set(runs.flatMap((r) => r.flags))].filter((f) =>
    runs.every((r) => r.flags.includes(f)),
  );
  const perRun = flagged
    .map((r) => [r.testId, r.id, r.flags.filter((f) => !universal.includes(f))] as const)
    .filter(([, , fs]) => fs.length);
  const events: (string | number)[][] = (["extinction", "blowoff", "no-ignition"] as const).map((e) => [
    e,
    runs.filter((r) => r.events.includes(e)).length,
  ]);
  events.push(["no event recorded", runs.filter((r) => r.events.length === 0).length]);

  return `## ${g.psiId} (${g.name})

Source: \`data/raw/${g.file}\` · ${g.url}

- Runs: **${runs.length}**
- Runs with a recorded starting oxygen: **${runs.filter((r) => r.o2InitialPct !== null).length}**
- Flagged runs: **${flagged.length}**
- Rows skipped: **${g.skipped.length}**
${g.skipped.map((s) => `  - line ${s.line}: "${s.text}" (${s.reason})`).join("\n")}

### Runs per PI

${table(["PI", "Runs"], [...count(runs.map((r) => r.pi))])}

### Runs per material family

${table(["Family", "Runs"], [...count(runs.map((r) => r.material.family))].sort((a, b) => b[1] - a[1]))}

### Runs per starting O2 band (% by volume, lower-inclusive)

${table(["Starting O2", "Runs"], o2Rows(runs))}

### Events

A run can have more than one event. "No event recorded" means the table records no outcome word, not that nothing happened.

${table(["Event", "Runs"], events)}

### Flag totals

${table(["Flag", "Runs"], [...count(runs.flatMap((r) => r.flags.map(flagKind)))].sort((a, b) => b[1] - a[1]))}

### Flags by test
${universal.length ? `\nEvery run in this table carries: ${universal.map((f) => `*${f}*`).join("; ")}. Listed below: the other flags.\n` : ""}
${perRun.length ? `| Test | Run id | Flags |\n|---|---|---|\n${perRun.map(([t, id, fs]) => `| ${t} | ${id} | ${fs.join("; ")} |`).join("\n")}` : "No other flags."}
`;
}

export function buildCombinedReport(groups: ReportGroup[]): string {
  const all = groups.flatMap((g) => g.runs);
  const withO2 = all.filter((r) => r.o2InitialPct !== null);
  const totals = groups.map((g) => [
    `${g.psiId} (${g.name})`,
    g.runs.length,
    g.runs.filter((r) => r.o2InitialPct !== null).length,
    g.runs.filter((r) => r.flags.length).length,
    g.skipped.length,
  ]);
  totals.push([
    "**All**",
    all.length,
    withO2.length,
    all.filter((r) => r.flags.length).length,
    groups.reduce((n, g) => n + g.skipped.length, 0),
  ]);

  return `# PSI import report

Generated by \`npm run import:psi\` (\`pipeline/psi_import_all.ts\`) from the raw tables in \`data/raw\`.
Do not edit by hand. Column notes: \`psi_bass2_columns.md\`, \`psi_bass_columns.md\`, \`psi_saffire_columns.md\`.

## Combined totals

${table(["Investigation", "Runs", "With starting O2", "Flagged runs", "Rows skipped"], totals)}

- Highest recorded starting oxygen: **${Math.max(...withO2.map((r) => r.o2InitialPct!))}%**; runs at 23% or more: **${withO2.filter((r) => r.o2InitialPct! >= 23).length}**.

### All runs per starting O2 band

${table(["Starting O2", "Runs"], o2Rows(all))}

### All runs per material family

${table(["Family", "Runs"], [...count(all.map((r) => r.material.family))].sort((a, b) => b[1] - a[1]))}

${groups.map(section).join("\n")}`;
}
