// Person A — checks every recorded-limit point (lib/limits.ts) against the raw
// PSI-25 BASS-II CSV in data/raw and writes pipeline/limits_report.md.
// Run: npx tsx pipeline/limits_report.ts   (exits 1 if any check fails)
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import runsJson from "../data/runs.json";
import { airText, limitCandidates, limitPoints, type LimitEvent } from "../lib/limits";
import type { Run } from "../lib/schema";
import { collapse, loadRawRows, type RawRow } from "./psi_import_bass2";
import { ROOT } from "./psi_shared";

export const REPORT_PATH = join(ROOT, "pipeline", "limits_report.md");
const EVENTS: LimitEvent[] = ["extinction", "blowoff", "no-ignition"];
/** Raw keyword for each event, as parseEvents in psi_import_bass2.ts reads it. */
const KEYWORD: Record<LimitEvent, RegExp> = {
  extinction: /ext|\bout\b/i,
  blowoff: /blowoff/i,
  "no-ignition": /no ign|would not stay lit/i,
};

export type Counts = Record<LimitEvent, { candidates: number; included: number; excluded: number }>;

export function limitCounts(runs: Run[]): Counts {
  const { points, excluded } = limitPoints(runs);
  const cands = limitCandidates(runs);
  return Object.fromEntries(
    EVENTS.map((e) => [
      e,
      {
        candidates: cands.filter((c) => c.event === e).length,
        included: points.filter((p) => p.event === e).length,
        excluded: excluded.filter((x) => x.event === e).length,
      },
    ]),
  ) as Counts;
}

const cell = (s: string) => (s ? s.replace(/\|/g, "\\|") : "_(blank)_");

/** Checks one point or exclusion against its raw row; returns failed checks. */
function rawChecks(
  row: RawRow | undefined,
  item: { event: LimitEvent; rawFlow: string },
  point?: { o2Pct: number; flowCmS: number; flowMaxCmS?: number; relation: string },
): string[] {
  if (!row) return ["no raw row with this test id"];
  const fails: string[] = [];
  const rawAir = collapse(row.air);
  if (collapse(airText(item.rawFlow)) !== rawAir) fails.push("air text differs from raw");
  if (!KEYWORD[item.event].test(`${row.fan} ${row.air}`)) fails.push(`no ${item.event} keyword in raw fan/air text`);
  if (point) {
    if (Number(collapse(row.o2Initial)) !== point.o2Pct) fails.push(`raw initial O2 "${row.o2Initial}" ≠ ${point.o2Pct}`);
    const nums = (rawAir.match(/\d+(?:\.\d+)?/g) ?? []).map(Number);
    if (!nums.includes(point.flowCmS)) fails.push(`flow ${point.flowCmS} not in raw air text`);
    if (point.flowMaxCmS !== undefined && !nums.includes(point.flowMaxCmS))
      fails.push(`flow ${point.flowMaxCmS} not in raw air text`);
    if (point.relation === "at") {
      const word = item.event === "extinction" ? "ext" : "blowoff";
      if (!new RegExp(`(^|\\s)${point.flowCmS}\\s*${word}`, "i").test(rawAir))
        fails.push(`raw air text does not put "${word}" right after ${point.flowCmS}`);
    }
  }
  return fails;
}

export function buildLimitsReport(runs: Run[], raw: RawRow[]): { markdown: string; failures: string[] } {
  const { points, excluded } = limitPoints(runs);
  const counts = limitCounts(runs);
  const byTest = new Map(raw.map((r) => [collapse(r.test), r]));
  const failures: string[] = [];

  const included = points.map((p) => {
    const row = byTest.get(p.testId);
    const fails = rawChecks(row, p, p);
    failures.push(...fails.map((f) => `${p.testId} ${p.event}: ${f}`));
    const flow = p.relation === "across" ? `${p.flowCmS}–${p.flowMaxCmS}` : `${p.relation === "below" ? "< " : ""}${p.flowCmS}`;
    return `| ${p.testId} | ${p.family} | ${p.event} | ${p.relation} | ${flow} | ${p.o2Pct} | ${p.o2FinalPct ?? "—"} | ${cell(row?.air ?? "")} | ${cell(row?.fan ?? "")} | ${cell(row?.o2Initial ?? "")} | ${p.flags.join("; ") || "—"} | ${fails.length ? "✗ " + fails.join("; ") : "✓"} |`;
  });
  const out = excluded.map((x) => {
    const row = byTest.get(x.testId);
    const fails = rawChecks(row, x);
    failures.push(...fails.map((f) => `${x.testId} ${x.event} (excluded): ${f}`));
    return `| ${x.testId} | ${x.family} | ${x.event} | ${x.reason} | ${cell(row?.air ?? "")} | ${cell(row?.fan ?? "")} | ${x.flags.join("; ") || "—"} | ${fails.length ? "✗ " + fails.join("; ") : "✓"} |`;
  });

  const total = (k: "candidates" | "included" | "excluded") => EVENTS.reduce((n, e) => n + counts[e][k], 0);
  const markdown = `# Recorded flammability limits: PSI-25 (BASS-II)

Generated by \`npx tsx pipeline/limits_report.ts\` from \`data/runs.json\`, with every point re-checked
against the raw table \`data/raw/PSI-25_Experimental table_BASS-II.csv\` (columns "Fan display",
"Air display", "Calibrated initial O2 % by vol"). Logic: \`lib/limits.ts\`.

Rules:
- A candidate is a PSI-25 run with an event keyword (extinction, blowoff, no ignition); a run with two events gives two candidates.
- Extinction flow is the last recorded airflow step before "ext" (\`flowCmS.min\`). Relation "at": the raw air text puts "ext" right after that step. Relation "below": the crew lowered the flow further on fan settings that were not converted to cm/s ("down to ext"), so the flame went out below that step. The value is never estimated.
- Blowoff flow is the step where blowoff occurred (\`flowCmS.max\`), only when the raw air text puts "blowoff" right after it.
- No ignition: the recorded steps at which the sample did not ignite or stay lit.
- Oxygen is the calibrated initial O2 as recorded; final O2 is shown when present.
- Anything ambiguous is excluded with the reason below. Nothing is fitted or extrapolated.

## Counts

| Event | Candidates | Included | Excluded |
|---|---|---|---|
${EVENTS.map((e) => `| ${e} | ${counts[e].candidates} | ${counts[e].included} | ${counts[e].excluded} |`).join("\n")}
| **total** | **${total("candidates")}** | **${total("included")}** | **${total("excluded")}** |

<!-- counts: ${JSON.stringify(counts)} -->

Raw checks: ${failures.length ? `**${failures.length} failed**` : "all passed"} (air text equals the raw "Air display" cell, event keyword present in the raw fan/air text, starting O2 equals the raw calibrated initial O2, flow value present in the raw air text, and for "at" the keyword directly follows the flow value).

## Included points (${points.length})

| Test | Material | Event | Relation | Flow (cm/s) | O2 start % | O2 final % | Raw air display | Raw fan display | Raw initial O2 | Flags | Raw check |
|---|---|---|---|---|---|---|---|---|---|---|---|
${included.join("\n")}

## Excluded candidates (${excluded.length})

| Test | Material | Event | Reason | Raw air display | Raw fan display | Flags | Raw check |
|---|---|---|---|---|---|---|---|
${out.join("\n")}
`;
  return { markdown, failures };
}

function main() {
  const { markdown, failures } = buildLimitsReport(runsJson as Run[], loadRawRows());
  writeFileSync(REPORT_PATH, markdown);
  if (failures.length) {
    console.error(`✗ ${failures.length} raw check(s) failed:\n  - ${failures.join("\n  - ")}`);
    process.exit(1);
  }
  console.log(`✓ wrote ${REPORT_PATH}; all raw checks passed`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
