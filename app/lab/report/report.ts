// Person A — the data of a printable scenario report. Pure: it only calls the Lab's
// own functions (matching, gaps, limits, findings, run order) and arranges what they
// return. No new scoring, no new thresholds.
import { LIMITS_INVESTIGATION, limitsForScenario, type LimitsView } from "../../../lib/limits";
import { matchInvestigations } from "../../../lib/match";
import type { Finding, Investigation, InvestigationMatch, Run, Scenario } from "../../../lib/schema";
import { BRIEF_URL } from "../../brief/brief-text";
import { relevantFindings, type MatchedFinding } from "../findings";
import { evidenceGaps, type GapReport } from "../gaps";
import { PARTIAL_GRAVITY_SOURCES } from "../gravity-bounds-note";
import { matchingRunIdSet } from "../matching-runs";
import { GRAVITY_LABEL, presets, PRESSURE_CONTEXT_NOTE, scenarioToQuery, type Preset } from "../scenario";
import { inTableOrder } from "../run-order";
import { investigationLabel } from "../summary";

/** How many ranked investigations and matching runs the printed report lists. */
export const REPORT_TOP_INVESTIGATIONS = 5;
export const REPORT_MAX_RUNS = 10;

export const REPORT_FOOTER =
  "Generated by Firebreak from NASA PSI data. Not affiliated with or endorsed by NASA. Firebreak ranks evidence; it does not rate fire risk or predict behaviour beyond tested conditions.";

export const NO_SCENARIO_TEXT =
  "No scenario is set. Pick a preset or set a material, oxygen, airflow, gravity or safety area in the Lab, then open the report from there.";

/** Link from the Lab to the report: the same URL parameters the Lab itself reads. */
const withQuery = (path: string, s: Scenario) => {
  const query = scenarioToQuery(s);
  return query ? `${path}?${query}` : path;
};
export const reportHref = (s: Scenario) => withQuery("/lab/report", s);
export const labHref = (s: Scenario) => withQuery("/lab", s);

const FIELDS = ["materialFamily", "o2Pct", "flowCmS", "pressurePsi", "gravity", "safetyArea"] as const;

/** Presets whose values are exactly the scenario's (every field, none extra). */
export function matchingPresets(scenario: Scenario, list: Preset[]): Preset[] {
  return list.filter((p) => FIELDS.every((k) => p.scenario[k] === scenario[k]));
}

export type Source = { label: string; url: string };

export type ScenarioReport = {
  generatedOn: string;
  labUrl: string;
  scenario: Scenario;
  fields: { label: string; value: string }[];
  presets: Preset[];
  gaps: GapReport;
  ranked: InvestigationMatch[];
  /** Imported investigations with a score of 0, not listed. */
  unlisted: number;
  withRuns: Set<string>;
  matching: { total: number | null; shown: Run[] };
  limits: LimitsView;
  findings: MatchedFinding[];
  caveats: { partialGravity: boolean; pressure: boolean };
  sources: Source[];
};

export type ReportInput = {
  scenario: Scenario;
  runs: Run[];
  investigations: Investigation[];
  /** Findings whose quotes were verified against the corpus (verifiedFindings). */
  findings: Finding[];
  generatedOn: string;
  /** Scheme and host the report was requested on, e.g. "https://example.org"; null when unknown. */
  origin: string | null;
};

export function buildScenarioReport(input: ReportInput): ScenarioReport {
  const { scenario, runs, investigations } = input;
  const matches = matchInvestigations(scenario, investigations, runs);
  const listed = matches.filter((m) => m.score > 0);
  const ranked = listed.slice(0, REPORT_TOP_INVESTIGATIONS);
  const matchSet = matchingRunIdSet(scenario, matches);
  const gaps = evidenceGaps(scenario, runs, investigations);
  const limits = limitsForScenario(scenario, runs);
  const findings = relevantFindings(scenario, input.findings);
  const shown = matchSet ? inTableOrder(runs.filter((r) => matchSet.has(r.id))).slice(0, REPORT_MAX_RUNS) : [];
  const matched = matchingPresets(scenario, presets(runs));

  const unset = "not set";
  const fields = [
    { label: "Material", value: scenario.materialFamily ?? unset },
    { label: "Starting oxygen", value: scenario.o2Pct !== undefined ? `${scenario.o2Pct}%` : unset },
    { label: "Airflow", value: scenario.flowCmS !== undefined ? `${scenario.flowCmS} cm/s` : unset },
    { label: "Gravity", value: scenario.gravity ? GRAVITY_LABEL[scenario.gravity] : unset },
    { label: "Pressure (context only)", value: scenario.pressurePsi !== undefined ? `${scenario.pressurePsi} psi` : unset },
    { label: "Safety area", value: scenario.safetyArea ?? unset },
  ];

  return {
    generatedOn: input.generatedOn,
    labUrl: `${input.origin ?? ""}${labHref(scenario)}`,
    scenario,
    fields,
    presets: matched,
    gaps,
    ranked,
    unlisted: matches.length - listed.length,
    withRuns: new Set(runs.map((r) => r.investigationId)),
    matching: { total: matchSet ? matchSet.size : null, shown },
    limits,
    findings,
    caveats: { partialGravity: gaps.partialGravity === true, pressure: scenario.pressurePsi !== undefined },
    sources: collectSources({ scenario, matched, gaps, ranked, shown, limits, findings, investigations }),
  };
}

type SourceParts = {
  scenario: Scenario;
  matched: Preset[];
  gaps: GapReport;
  ranked: InvestigationMatch[];
  shown: Run[];
  limits: LimitsView;
  findings: MatchedFinding[];
  investigations: Investigation[];
};

/** Every external URL the report cites, once, in order of first mention. */
function collectSources(p: SourceParts): Source[] {
  const found = new Map<string, string>();
  const add = (label: string, url: string | undefined) => {
    if (url && !found.has(url)) found.set(url, label);
  };
  const psi = (id: string) => {
    const inv = p.investigations.find((i) => i.id === id);
    return inv ? add(`PSI page: ${investigationLabel(inv)} (${inv.id})`, inv.url) : undefined;
  };
  const brief = "NASA Space Apps 2026 challenge brief, Flame in Freefall";

  for (const preset of p.matched) {
    add(preset.sourceUrl ? preset.source : brief, preset.sourceUrl);
    // A source line that cites the brief without a link of its own.
    if (!preset.sourceUrl && /challenge brief/.test(preset.source)) add(brief, BRIEF_URL);
  }
  if (p.gaps.aboveSolidO2 !== undefined || p.gaps.partialGravity) add(brief, BRIEF_URL);
  if (p.gaps.partialGravity) {
    const { gollner, fm2 } = PARTIAL_GRAVITY_SOURCES;
    add(`${gollner.label}, NTRS ${gollner.ntrs}`, gollner.url);
    add(`${fm2.label}, NTRS ${fm2.ntrs}`, fm2.url);
  }
  for (const m of p.ranked) add(`PSI page: ${investigationLabel(m.investigation)} (${m.investigation.id})`, m.investigation.url);
  for (const r of p.shown) psi(r.investigationId);
  if (p.limits.kind === "limits") psi(LIMITS_INVESTIGATION);
  for (const { finding: f } of p.findings) add(f.sourceTitle, f.url);
  return [...found].map(([url, label]) => ({ label, url }));
}

/** Preset sources shown once even when several presets share the same values. */
export const distinctSources = (list: Preset[]) => [...new Set(list.map((p) => p.source))];

